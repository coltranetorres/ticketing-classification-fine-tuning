def main() -> None:
    assert set(DATA) == set(LABELS), set(DATA) ^ set(LABELS)
    assert all(len(v) == 10 for v in DATA.values())
    texts = [u for v in DATA.values() for u in v]
    assert len(texts) == len(set(texts)) == 270
    out = Path("data/holdout/synthetic_holdout.jsonl")
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w") as f:
        for intent in sorted(DATA):
            for u in DATA[intent]:
                f.write(json.dumps({"utterance": u, "intent": intent}) + "\n")
    print(f"wrote {len(texts)} rows to {out}")


if __name__ == "__main__":
    main()
